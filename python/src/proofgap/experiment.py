"""Run every variant through every tier and write a detection matrix.

    uv run python -m proofgap.experiment    # print + write RESULTS.md and results.json
"""

from __future__ import annotations

import json
import platform
import sys
import time
from pathlib import Path

from . import spec
from .compiler import compile_program
from .legacy import LedgerService, as_function
from .tiers import TIERS, TierResult, Variant


def compiled(name, layer, story, source, **bugs) -> Variant:
    fn, src = compile_program(source, **bugs)
    return Variant(name, layer, story, fn, source, source, src)


def variants() -> list[Variant]:
    return [
        compiled("baseline (compiled)", "-", "Correct source, correct compiler.", spec.SPEC),
        compiled("fee not debited", "source",
                 "Payer charged the amount but not the fee; money is created.",
                 spec.spec_fee_not_debited()),
        compiled("fee helper drift", "source",
                 "Affordability check uses the floor-rounded quote fee, debit uses the "
                 "ceiling ledger fee: 1p overdraft when balance == amount + fee - 1.",
                 spec.spec_fee_helper_drift()),
        compiled("fee helper drift, ≥ £1m only", "source",
                 "The same drift, but only on the high-value (≥ £1m) path.",
                 spec.spec_fee_helper_drift_high_value()),
        compiled("fee paid to payee", "source",
                 "Fee credited to the payee, not the bank. Every stated promise still holds.",
                 spec.spec_fee_to_payee()),
        compiled("compiler: associativity", "compiler",
                 "Codegen treats '-' as associative: a - (b + c) becomes a - b + c.",
                 spec.SPEC, assoc_bug=True),
        compiled("compiler: ceil template", "compiler",
                 "Misplaced parenthesis turns ceiling division into floor division.",
                 spec.SPEC, ceil_bug=True),
        Variant("legacy service", "legacy", "Hand-written Python, correct.",
                as_function(LedgerService()), None, spec.SPEC),
        Variant("legacy: strict check", "legacy",
                "Hand-written Python with '<' instead of '<=' in the affordability check: "
                "you can no longer spend your whole balance.",
                as_function(LedgerService(strict_affordability=True)), None, spec.SPEC),
    ]


MARK = {"caught": "CAUGHT", "missed": "·", "n/a": "n/a"}


def run() -> tuple[list[Variant], dict[str, dict[str, TierResult]], float]:
    t0 = time.perf_counter()
    vs = variants()
    results: dict[str, dict[str, TierResult]] = {}
    for v in vs:
        results[v.name] = {}
        for tier, fn in TIERS.items():
            t = time.perf_counter()
            results[v.name][tier] = r = fn(v)
            r.seconds = time.perf_counter() - t
            print(f"  {v.name:<30} {tier:<12} {MARK[r.status]:<7} {r.detail}", file=sys.stderr)
    return vs, results, time.perf_counter() - t0


def matrix(vs, results) -> str:
    head = "| variant | bug lives in | " + " | ".join(TIERS) + " |"
    sep = "|---|---|" + "---|" * len(TIERS)
    rows = [f"| {v.name} | {v.layer} | " +
            " | ".join(f"**{MARK[results[v.name][t].status]}**" if results[v.name][t].status == "caught"
                       else MARK[results[v.name][t].status] for t in TIERS) + " |"
            for v in vs]
    return "\n".join([head, sep, *rows])


def only_catcher(vs, results) -> list[str]:
    lines = []
    for v in vs:
        caught = [t for t in TIERS if results[v.name][t].status == "caught"]
        if len(caught) == 1:
            lines.append(f"- **{v.name}**: only **{caught[0]}** catches it.")
        elif not caught and v.layer != "-" and v.name != "legacy service":
            lines.append(f"- **{v.name}**: nothing catches it.")
    return lines


def report(vs, results, seconds) -> str:
    out = [
        "# Results",
        "",
        ("Generated by `uv run python -m proofgap.experiment`. Hypothesis runs are "
        "derandomized, so re-running gives the same table."),
        "",
        "## Detection matrix",
        "",
        matrix(vs, results),
        "",
        ("`CAUGHT` = the tier reports a failure. `·` = the tier passes (the bug gets through). "
        "`n/a` = the tier cannot be applied."),
        "",
        "## Bugs only one tier catches",
        "",
        *only_catcher(vs, results),
        "",
        "## Evidence",
        "",
    ]
    for v in vs:
        out += [f"### {v.name}", "", f"_{v.story}_", ""]
        for t in TIERS:
            r = results[v.name][t]
            label = {"caught": "fails, bug caught", "missed": "passes", "n/a": "not applicable"}[r.status]
            out.append(f"- **{t}** ({label}): {r.detail}")
        out.append("")
    gen = {v.name: v.generated for v in vs if v.generated}
    out += ["## What the compiler emitted", "",
            "The proof covers the DSL source. These are what actually ran.", ""]
    for name in ("baseline (compiled)", "compiler: associativity", "compiler: ceil template"):
        out += [f"**{name}**", "", "```python", gen[name].rstrip(), "```", ""]
    out.append(f"_Total runtime: {seconds:.1f}s._")
    return "\n".join(out) + "\n"


def to_json(vs, results, seconds) -> dict:
    """Machine-readable results, same shape as the Rust lab's results.json."""
    from importlib.metadata import version

    import z3
    return {
        "language": "python",
        "versions": {"python": platform.python_version(), "z3": z3.get_full_version(),
                     "property_testing": f"hypothesis {version('hypothesis')}"},
        "order": [v.name for v in vs],
        "variants": {
            v.name: {"layer": v.layer,
                     "tiers": {t: {"status": r.status, "detail": r.detail, "witness": r.witness,
                                   "seconds": r.seconds}
                               for t, r in results[v.name].items()}}
            for v in vs
        },
        "total_seconds": seconds,
    }


def main() -> None:
    vs, results, seconds = run()
    md = report(vs, results, seconds)
    Path("RESULTS.md").write_text(md)
    Path("results.json").write_text(json.dumps(to_json(vs, results, seconds), indent=2, ensure_ascii=False) + "\n")
    print()
    print(matrix(vs, results))
    print()
    print("\n".join(only_catcher(vs, results)))
    print(f"\nWrote RESULTS.md and results.json ({seconds:.1f}s)")


if __name__ == "__main__":
    main()
