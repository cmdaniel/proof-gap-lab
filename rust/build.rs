#![allow(dead_code)]
//! Runs the unverified DSL -> Rust compiler at build time. The generated
//! functions are then compiled by rustc and linked into the library, so the
//! code under test really is "source -> untrusted compiler -> native binary".

#[path = "src/catalog.rs"]
mod catalog;
#[path = "src/compiler.rs"]
mod compiler;
#[path = "src/dsl.rs"]
mod dsl;
#[path = "src/spec.rs"]
mod spec;

use std::fmt::Write as _;

fn main() {
    for f in [
        "src/catalog.rs",
        "src/compiler.rs",
        "src/dsl.rs",
        "src/spec.rs",
    ] {
        println!("cargo:rerun-if-changed={f}");
    }
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let version = std::process::Command::new(rustc)
        .arg("--version")
        .output()
        .unwrap()
        .stdout;
    println!(
        "cargo:rustc-env=RUSTC_VERSION={}",
        String::from_utf8_lossy(&version).trim()
    );

    let mut out = String::from("// @generated by build.rs from the DSL. Do not edit.\n\n");
    let mut table = String::from(
        "pub const COMPILED_FNS: &[(&str, fn(i64, i64, i64) -> (i64, i64, i64), &str)] = &[\n",
    );
    for v in catalog::COMPILED {
        let src = compiler::to_source(&(v.source)(), v.ident, v.bugs);
        writeln!(
            out,
            "#[allow(unused_variables, unused_parens, clippy::all)]\n{src}"
        )
        .unwrap();
        writeln!(table, "    ({:?}, {}, {:?}),", v.name, v.ident, src).unwrap();
    }
    table.push_str("];\n");
    out.push_str(&table);
    let path = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("generated.rs");
    std::fs::write(path, out).unwrap();
}
