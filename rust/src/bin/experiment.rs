//! Run every variant through every tier; write RESULTS.md and results.json.
//!
//!     cargo run --release --bin experiment

use std::time::Instant;

use proofgap::checker::overflow_obligations;
use proofgap::tiers::{Outcome, TIERS, TierResult, run_tier};
use proofgap::{spec, variants};
use serde_json::{Map, Value, json};

fn mark(r: &TierResult) -> &'static str {
    match r.status {
        Outcome::Caught => "**CAUGHT**",
        Outcome::Missed => "·",
        Outcome::NotApplicable => "n/a",
    }
}

fn main() {
    let t0 = Instant::now();
    let vs = variants();
    let mut rows: Vec<Vec<TierResult>> = vec![];
    for v in &vs {
        let mut row = vec![];
        for tier in TIERS {
            let r = run_tier(tier, v);
            eprintln!(
                "  {:<30} {:<12} {:<7} {}",
                v.name,
                tier,
                r.status.key(),
                r.detail
            );
            row.push(r);
        }
        rows.push(row);
    }
    let seconds = t0.elapsed().as_secs_f64();

    // Rust-only: does every integer subterm of the proved source fit in i64?
    let (checked, overflowing) = overflow_obligations(&spec::spec());

    let mut matrix = format!(
        "| variant | bug lives in | {} |\n|---|---|{}\n",
        TIERS.join(" | "),
        "---|".repeat(TIERS.len())
    );
    for (v, row) in vs.iter().zip(&rows) {
        matrix += &format!(
            "| {} | {} | {} |\n",
            v.name,
            v.layer,
            row.iter().map(mark).collect::<Vec<_>>().join(" | ")
        );
    }
    let mut only = vec![];
    for (v, row) in vs.iter().zip(&rows) {
        let caught: Vec<&str> = TIERS
            .iter()
            .zip(row)
            .filter(|(_, r)| r.status == Outcome::Caught)
            .map(|(t, _)| *t)
            .collect();
        if caught.len() == 1 {
            only.push(format!(
                "- **{}**: only **{}** catches it.",
                v.name, caught[0]
            ));
        }
    }

    let mut md = String::from(
        "# Results (Rust)\n\nGenerated by `cargo run --release --bin experiment`. proptest runs use a fixed \
         ChaCha seed, so re-running gives the same table.\n\n## Detection matrix\n\n",
    );
    md += &matrix;
    md += "\n`CAUGHT` = the tier reports a failure. `·` = the tier passes (the bug gets through). \
           `n/a` = the tier cannot be applied.\n\n## Bugs only one tier catches\n\n";
    md += &only.join("\n");
    md += &format!(
        "\n\n## Overflow obligations (Rust only)\n\nThe proof uses mathematical integers; the compiled code uses `i64`. \
         Z3 checked {checked} integer subterms of the spec over the whole input domain: {}.\n\n## Evidence\n\n",
        if overflowing.is_empty() {
            "every one fits in `i64`, so no overflow is possible".to_string()
        } else {
            format!("{} can overflow: {:?}", overflowing.len(), overflowing)
        }
    );
    for (v, row) in vs.iter().zip(&rows) {
        md += &format!("### {}\n\n_{}_\n\n", v.name, v.story);
        for (t, r) in TIERS.iter().zip(row) {
            let label = match r.status {
                Outcome::Caught => "fails, bug caught",
                Outcome::Missed => "passes",
                Outcome::NotApplicable => "not applicable",
            };
            md += &format!("- **{t}** ({label}): {}\n", r.detail);
        }
        md += "\n";
    }
    md += "## What the compiler emitted\n\nThe proof covers the DSL source. These are what rustc compiled and ran.\n\n";
    for name in [
        "baseline (compiled)",
        "compiler: associativity",
        "compiler: ceil template",
    ] {
        let v = vs.iter().find(|v| v.name == name).unwrap();
        md += &format!(
            "**{name}**\n\n```rust\n{}```\n\n",
            v.generated.as_ref().unwrap()
        );
    }
    md += &format!("_Total runtime (release build): {seconds:.1}s._\n");
    std::fs::write("RESULTS.md", md).unwrap();

    let mut variants_json = Map::new();
    for (v, row) in vs.iter().zip(&rows) {
        let mut tiers = Map::new();
        for (t, r) in TIERS.iter().zip(row) {
            tiers.insert(
                t.to_string(),
                json!({"status": r.status.key(), "detail": r.detail,
                       "witness": r.witness.map(|w| json!({"src": w[0], "dst": w[1], "amount": w[2]})),
                       "seconds": r.seconds}),
            );
        }
        variants_json.insert(
            v.name.clone(),
            json!({"layer": v.layer, "tiers": Value::Object(tiers)}),
        );
    }
    let out = json!({
        "language": "rust",
        "versions": {"rustc": env!("RUSTC_VERSION"), "z3": z3::full_version(), "property_testing": "proptest 1.12"},
        "order": vs.iter().map(|v| v.name.clone()).collect::<Vec<_>>(),
        "variants": Value::Object(variants_json),
        "overflow_obligations": {"checked": checked, "overflowing": overflowing},
        "total_seconds": seconds,
    });
    std::fs::write(
        "results.json",
        serde_json::to_string_pretty(&out).unwrap() + "\n",
    )
    .unwrap();

    println!(
        "\n{matrix}\n{}\n\nWrote RESULTS.md and results.json ({seconds:.1}s)",
        only.join("\n")
    );
}
